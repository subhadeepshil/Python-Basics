#1 WAP to find the sum of first n number(using while loop)
n= 5
sum=0

i=1
while i <= n:                    #it will find the sum of the first n numbers by iterating through the numbers from 1 to n and adding them to the variable sum.
    sum += i
    i += 1
for i in range(1,n+1):                    #it will find the sum of the first n numbers by iterating through the numbers from 1 to n and adding them to the variable sum.
    sum += i









