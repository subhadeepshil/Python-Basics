#union and intersection of sets
set1={1,2,3,4}
set2={5,3,2,1}

print(set1.union(set2))          #to find the union of two sets we use the union() method
print(set2)
print(set1)


#intersection of sets
print(set1.intersection(set2))   #to find the intersection of two sets we use the intersection() method
print(set2)